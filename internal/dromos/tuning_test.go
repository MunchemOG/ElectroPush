// Both written exactly as TuningFile and AutoTuningFile write them.
const robotTuning = `// Generated by ElectroDromos. Re-run the tuners to update; don't hand-edit.
package org.firstinspires.ftc.teamcode.tuning;

import me.munchem.electrodromos.tuning.TunedBy;

public final class DromosTuning {
    private DromosTuning() {}

    @TunedBy("Path limits tuner, 2026-10-05")
    public static final double MAX_LATERAL_ACCEL = 61.3;

    @TunedBy("Path limits tuner, 2026-10-05")
    public static final double MAX_TURN_RATE = 5.9;

    @TunedBy("Voltage tuner, 2026-10-04, spread 0.21 V")
    public static final double NOMINAL_VOLTAGE = 12.62;

    @TunedBy("Spin Check, 2026-10-04, drift 0.08 in")
    public static final double X_POD_OFFSET = 0.42;
}
`

const starterTuning = `// Generated by ElectroDromos. Re-run the tuners to update; don't hand-edit.
package org.firstinspires.ftc.teamcode.tuning;

public final class DromosTuning {
    private DromosTuning() {}

    public static final double MAX_LATERAL_ACCEL = 40.0;

    public static final double MAX_TURN_RATE = 3.0;

    public static final double NOMINAL_VOLTAGE = 12.0;
}
`

const robotAuto = `// Generated by ElectroDromos. Re-run the path tuner for RedNear to update; don't hand-edit.
package org.firstinspires.ftc.teamcode.tuning;

import me.munchem.electrodromos.auto.AutoTuning;

public final class RedNearTuning implements AutoTuning {
    @Override
    public String tunedBy() {
        return "Path tuner, 2026-10-06, 3 rounds, every pose under 0.5 in";
    }

    @Override
    public void poses(Corrections corrections) {
        // name, designed x, y, heading, corrected x, y, heading, run-to-run spread
        corrections.add("PICKUP", 30.0, 20.0, -1.5708, 30.41, 19.12, -1.561, 0.18);
        corrections.add("SCORE", 40.0, 70.0, 0.7854, 40.62, 69.4, 0.7801, 0.21);
    }

    @Override
    public boolean robotUnchanged() {
        return DromosTuning.MAX_LATERAL_ACCEL == 61.3
                && DromosTuning.NOMINAL_VOLTAGE == 12.62;
    }
}
`

func TestAPulledFileGoesWhereItsPackageSays(t *testing.T) {
	root := t.TempDir()
	f, err := place(root, "DromosTuning.java", []byte(robotTuning))
	if err != nil {
		t.Fatal(err)
	}
	want := filepath.Join(root, "TeamCode", "src", "main", "java", "org", "firstinspires", "ftc", "teamcode", "tuning", "DromosTuning.java")
	if f.Dest != want {
		t.Errorf("dest = %s, want %s", f.Dest, want)
	}
	if f.Local != nil || !f.Changed() {
		t.Error("a file the project lacks has to count as a change")
	}

	if _, err := place(root, "Broken.java", []byte("public class Broken {}")); err == nil {
		t.Error("a file with no package line cannot be placed, and must not be guessed at")
	}
}

func TestWhatAPullWouldChange(t *testing.T) {
	for _, tc := range []struct {
		name  string
		local string
		robot string
		want  []Change
	}{
		{
			name:  "the starter file, tuned for the first time",
			local: starterTuning,
			robot: robotTuning,
			want: []Change{
				{Name: "MAX_LATERAL_ACCEL", Old: "40.0", New: "61.3", Note: "Path limits tuner, 2026-10-05"},
				{Name: "MAX_TURN_RATE", Old: "3.0", New: "5.9", Note: "Path limits tuner, 2026-10-05"},
				{Name: "NOMINAL_VOLTAGE", Old: "12.0", New: "12.62", Note: "Voltage tuner, 2026-10-04, spread 0.21 V"},
				{Name: "X_POD_OFFSET", Old: "new", New: "0.42", Note: "Spin Check, 2026-10-04, drift 0.08 in"},
			},
		},
		{
			name:  "an auto tuned for the first time",
			robot: robotAuto,
			want: []Change{
				{Name: "PICKUP", Old: "designed", New: "30.41, 19.12, -1.561", Note: "Path tuner, 2026-10-06, 3 rounds, every pose under 0.5 in"},
				{Name: "SCORE", Old: "designed", New: "40.62, 69.4, 0.7801", Note: "Path tuner, 2026-10-06, 3 rounds, every pose under 0.5 in"},
			},
		},
		{
			name:  "an auto tuned again, with one pose moving",
			local: robotAuto,
			robot: strings.Replace(robotAuto, "40.62, 69.4, 0.7801", "40.55, 69.48, 0.7812", 1),
			want: []Change{
				{Name: "SCORE", Old: "40.62, 69.4, 0.7801", New: "40.55, 69.48, 0.7812", Note: "Path tuner, 2026-10-06, 3 rounds, every pose under 0.5 in"},
			},
		},
		{
			name:  "nothing moved",
			local: robotTuning,
			robot: robotTuning,
		},
	} {
		t.Run(tc.name, func(t *testing.T) {
			f := TuningFile{Robot: []byte(tc.robot)}
			if tc.local != "" {
				f.Local = []byte(tc.local)
			}
			got := f.Changes()
			if len(got) != len(tc.want) {
				t.Fatalf("got %d changes, want %d:\n%+v", len(got), len(tc.want), got)
			}
			for i := range got {
				if got[i] != tc.want[i] {
					t.Errorf("change %d = %+v, want %+v", i, got[i], tc.want[i])
				}
			}
		})
	}
}

// A team's own class that happens to share a generated file's name is theirs.
func TestAPullNeverOverwritesCodeElectroDromosDidNotWrite(t *testing.T) {
	root := t.TempDir()
	f, err := place(root, "RedNearTuning.java", []byte(robotAuto))
	if err != nil {
		t.Fatal(err)
	}

	mine := "package org.firstinspires.ftc.teamcode.tuning;\n\npublic class RedNearTuning { /* mine */ }\n"
	if err := os.MkdirAll(filepath.Dir(f.Dest), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(f.Dest, []byte(mine), 0o644); err != nil {
		t.Fatal(err)
	}
	f.Local = []byte(mine)

	if _, err := Write([]TuningFile{f}); err == nil {
		t.Error("overwrote a hand-written class")
	}
	if got, _ := os.ReadFile(f.Dest); string(got) != mine {
		t.Error("the hand-written class changed")
	}

	// The starter file is ElectroDromos's own, and is exactly what a pull is for.
	starter, _ := place(root, "DromosTuning.java", []byte(robotTuning))
	if err := os.WriteFile(starter.Dest, []byte(starterTuning), 0o644); err != nil {
		t.Fatal(err)
	}
	starter.Local = []byte(starterTuning)
	if _, err := Write([]TuningFile{starter}); err != nil {
		t.Fatal(err)
	}
	if got, _ := os.ReadFile(starter.Dest); string(got) != robotTuning {
		t.Error("the pulled file has to land byte for byte")
	}
}

func TestTellingAProjectUsesElectroDromos(t *testing.T) {
	plain := t.TempDir()
	if err := os.WriteFile(filepath.Join(plain, "build.dependencies.gradle"), []byte("implementation 'com.pedropathing:revhub:3.0.1'"), 0o644); err != nil {
		t.Fatal(err)
	}
	if UsesDromos(plain) {
		t.Error("a Pedro project without ElectroDromos is not one")
	}

	byDependency := t.TempDir()
	if err := os.WriteFile(filepath.Join(byDependency, "build.dependencies.gradle"), []byte("implementation 'me.munchem:electrodromos:0.0.1-PreAlpha'"), 0o644); err != nil {
		t.Fatal(err)
	}
	if !UsesDromos(byDependency) {
		t.Error("the dependency was not noticed")
	}

	byFile := t.TempDir()
	dir := filepath.Join(byFile, "TeamCode", "src", "main", "java", "org", "firstinspires", "ftc", "teamcode", "tuning")
	if err := os.MkdirAll(dir, 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(dir, "DromosTuning.java"), []byte(starterTuning), 0o644); err != nil {
		t.Fatal(err)
	}
	if !UsesDromos(byFile) {
		t.Error("the starter tuning file was not noticed")
	}
}
