// Package dromos is what epsh knows about ElectroDromos, the supplement to
// Pedro Pathing's path following: the tuning files its tuners write on the
// robot, and the runs Record Auto and the Path Tuner record there.
//
// Neither needs anything from ElectroDromos itself. Both are files in fixed
// folders under /sdcard/FIRST, written in formats ElectroDromos documents, so
// epsh reads them the way `adb pull` would and does the part `adb pull` cannot:
// put them in the right place, say what changed, and notice when they were
// forgotten.
package dromos

import (
	"bytes"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"

	"github.com/MunchemOG/ElectroPush/internal/adb"
)

// The folders ElectroDromos's tuners write into, under the robot's FIRST
// folder (TuningFile.FOLDER and RunFile.FOLDER).
const (
	RobotTuningDir = "/sdcard/FIRST/electrodromos/tuning"
	RobotRunsDir   = "/sdcard/FIRST/electrodromos/runs"
)

// generatedMarker starts every file ElectroDromos generates, the starter
// DromosTuning included. A file without it is somebody's own code, and is never
// overwritten.
const generatedMarker = "// Generated by ElectroDromos."

// javaRoot is where team sources live, relative to the project.
var javaRoot = filepath.Join("TeamCode", "src", "main", "java")

// TuningFile is one generated file the robot holds, and the project's copy of
// it.
type TuningFile struct {
	// Name is the file name, e.g. DromosTuning.java.
	Name string
	// Robot is the file as the robot holds it.
	Robot []byte
	// Dest is where it belongs in the project, from its package line.
	Dest string
	// Local is the project's copy, nil when the project has none.
	Local []byte
}

// Changed reports whether pulling it would change the project.
func (f TuningFile) Changed() bool { return !bytes.Equal(f.Robot, f.Local) }

// UsesDromos reports whether a project builds against ElectroDromos, so a
// deploy only asks the robot about tuning files when there can be any.
func UsesDromos(root string) bool {
	found := false
	filepath.Walk(filepath.Join(root, javaRoot), func(path string, info os.FileInfo, err error) error {
		if err != nil || found {
			return filepath.SkipDir
		}
		if !info.IsDir() && info.Name() == "DromosTuning.java" {
			found = true
		}
		return nil
	})
	if found {
		return true
	}

	for _, name := range []string{"build.dependencies.gradle", filepath.Join("TeamCode", "build.gradle"),
		filepath.Join("TeamCode", "build.gradle.kts"), filepath.Join("gradle", "libs.versions.toml")} {
		if data, err := os.ReadFile(filepath.Join(root, name)); err == nil && bytes.Contains(data, []byte("electrodromos")) {
			return true
		}
	}
	return false
}

var packageRe = regexp.MustCompile(`(?m)^\s*package\s+([A-Za-z_][A-Za-z0-9_.]*)\s*;`)

// Fetch reads every generated file the robot holds, and the project's copy of
// each.
func Fetch(serial, root string) ([]TuningFile, error) {
	out, err := adb.Shell(serial, "ls", RobotTuningDir, "2>/dev/null", "||", "true")
	if err != nil {
		return nil, fmt.Errorf("cannot look in %s: %w", RobotTuningDir, err)
	}

	var names []string
	for _, line := range strings.Split(out, "\n") {
		if name := strings.TrimSpace(line); strings.HasSuffix(name, ".java") {
			names = append(names, name)
		}
	}
	sort.Strings(names)
	if len(names) == 0 {
		return nil, nil
	}

	work, err := os.MkdirTemp("", "epsh-tuning-*")
	if err != nil {
		return nil, err
	}
	defer os.RemoveAll(work)

	var files []TuningFile
	for _, name := range names {
		local := filepath.Join(work, name)
		if err := adb.Pull(serial, RobotTuningDir+"/"+name, local); err != nil {
			return nil, fmt.Errorf("cannot pull %s: %w", name, err)
		}
		content, err := os.ReadFile(local)
		if err != nil {
			return nil, err
		}

		file, err := place(root, name, content)
		if err != nil {
			return nil, err
		}
		files = append(files, file)
	}
	return files, nil
}

// place works out where a generated file belongs and reads what is there now.
func place(root, name string, content []byte) (TuningFile, error) {
	match := packageRe.FindSubmatch(content)
	if match == nil {
		return TuningFile{}, fmt.Errorf("%s on the robot has no package line, so epsh cannot tell where it goes", name)
	}
	pkg := string(match[1])

	f := TuningFile{
		Name:  name,
		Robot: content,
		Dest:  filepath.Join(append([]string{root, javaRoot}, append(strings.Split(pkg, "."), name)...)...),
	}
	if existing, err := os.ReadFile(f.Dest); err == nil {
		f.Local = existing
	}
	return f, nil
}

// Write puts the robot's files into the project, byte for byte, the way
// `adb pull` would.
//
// Except that a file at the destination that ElectroDromos did not generate is
// left alone: a team class that happens to be called RedNearTuning is theirs,
// and a pull is not a reason to lose it.
func Write(files []TuningFile) ([]string, error) {
	var written []string
	for _, f := range files {
		if !f.Changed() {
			continue
		}
		if f.Local != nil && !bytes.HasPrefix(bytes.TrimSpace(f.Local), []byte(generatedMarker)) {
			return written, fmt.Errorf("%s exists and was not generated by ElectroDromos, so it was left alone: "+
				"rename it, or delete it if the robot's copy should replace it", f.Dest)
		}
		if err := os.MkdirAll(filepath.Dir(f.Dest), 0o755); err != nil {
			return written, err
		}
		if err := os.WriteFile(f.Dest, f.Robot, 0o644); err != nil {
			return written, err
		}
		written = append(written, f.Dest)
	}
	return written, nil
}

// Change is one value a pull would change.
type Change struct {
	Name string
	Old  string
	New  string
	// Note is the tuner's own account of it, from @TunedBy or tunedBy().
	Note string
}

// Changes is what pulling a file would change, value by value.
//
// Read for both kinds of generated file: DromosTuning's constants, and an
// auto's corrected poses. A file in neither shape still reports that it
// changed, through Changed, even when nothing here can say how.
func (f TuningFile) Changes() []Change {
	if !f.Changed() {
		return nil
	}

	var changes []Change

	old, oldNotes := constants(f.Local)
	now, notes := constants(f.Robot)
	for _, name := range sortedKeys(now, old) {
		was, had := old[name]
		is, has := now[name]
		switch {
		case !has:
			changes = append(changes, Change{Name: name, Old: was, New: "removed"})
		case !had:
			changes = append(changes, Change{Name: name, Old: "new", New: is, Note: notes[name]})
		case was != is:
			changes = append(changes, Change{Name: name, Old: was, New: is, Note: notes[name]})
		case notes[name] != oldNotes[name]:
			changes = append(changes, Change{Name: name, Old: was, New: is, Note: notes[name] + " (re-measured, same value)"})
		}
	}

	oldPoses := corrections(f.Local)
	nowPoses := corrections(f.Robot)
	note := tunedBy(f.Robot)
	for _, name := range sortedKeys(nowPoses, oldPoses) {
		was, had := oldPoses[name]
		is, has := nowPoses[name]
		switch {
		case !has:
			changes = append(changes, Change{Name: name, Old: was, New: "removed"})
		case !had:
			changes = append(changes, Change{Name: name, Old: "designed", New: is, Note: note})
		case was != is:
			changes = append(changes, Change{Name: name, Old: was, New: is, Note: note})
		}
	}

	return changes
}

var (
	constantRe = regexp.MustCompile(`(?m)(?:@TunedBy\("((?:[^"\\]|\\.)*)"\)\s*)?public\s+static\s+final\s+double\s+([A-Z][A-Z0-9_]*)\s*=\s*([^;]+);`)
	// corrections.add("NAME", designed x, y, h, corrected x, y, h, spread);
	correctionRe = regexp.MustCompile(`corrections\.add\("([A-Z][A-Z0-9_]*)",\s*([^,]+),\s*([^,]+),\s*([^,]+),\s*([^,]+),\s*([^,]+),\s*([^,]+),\s*([^)]+)\)`)
	tunedByRe    = regexp.MustCompile(`tunedBy\(\)\s*\{\s*return\s*"((?:[^"\\]|\\.)*)"`)
)

// constants reads DromosTuning's constants and their @TunedBy notes.
func constants(src []byte) (map[string]string, map[string]string) {
	values, notes := map[string]string{}, map[string]string{}
	for _, m := range constantRe.FindAllSubmatch(src, -1) {
		name := string(m[2])
		values[name] = strings.TrimSpace(string(m[3]))
		notes[name] = string(m[1])
	}
	return values, notes
}

// corrections reads an auto's corrected poses as "x, y, heading".
func corrections(src []byte) map[string]string {
	poses := map[string]string{}
	for _, m := range correctionRe.FindAllSubmatch(src, -1) {
		poses[string(m[1])] = fmt.Sprintf("%s, %s, %s",
			strings.TrimSpace(string(m[5])), strings.TrimSpace(string(m[6])), strings.TrimSpace(string(m[7])))
	}
	return poses
}

func tunedBy(src []byte) string {
	if m := tunedByRe.FindSubmatch(src); m != nil {
		return string(m[1])
	}
	return ""
}

func sortedKeys(maps ...map[string]string) []string {
	seen := map[string]bool{}
	var keys []string
	for _, m := range maps {
		for k := range m {
			if !seen[k] {
				seen[k] = true
				keys = append(keys, k)
			}
		}
	}
	sort.Strings(keys)
	return keys
}

// Pending is every file on the robot the project does not have as it is.
func Pending(files []TuningFile) []TuningFile {
	var pending []TuningFile
	for _, f := range files {
		if f.Changed() {
			pending = append(pending, f)
		}
	}
	return pending
}
